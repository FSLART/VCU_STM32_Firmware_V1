"""
VCU throttle map and settings editor - table + 3D view, Fueltech / Haltech style.

Tabs:
  Mapa                    Core/Inc/throttle_map_data.h: relative-current map (accelerator x
                          vehicle speed). The whole file is rewritten on save.
  Conducao                Driving #defines (regen, ramps, PAU, speed calculation).
  Tracao / Vetorizacao    Traction control (PI) and torque vectoring (traction_control_torque_vectoring.h).
  Calibracao / Seguranca  APPS calibration, BSPD, R2D, inverter brake limits.
                          Locked until "Desbloquear" is ticked.

Settings are edited IN PLACE: only the number on each '#define NAME <number>' line is
replaced; comments and everything else stay as they are. If a define is not found on
exactly one plain line where it is expected, every setting from that file is locked
(shown, never written) - the file is not as the tool expects, so writing it is not safe.
Every value is range checked, plus rule checks (APPS tolerance <= 10 % of pedal travel,
...). These are WARNINGS only: they are shown in red and listed before saving, and the
user decides whether to save anyway. Only a field that is not a number, or a locked
file, stops a save.

    python tools/throttle_map_editor.py             # open the editor
    python tools/throttle_map_editor.py --selftest  # check everything reads and writes back unchanged

Needs matplotlib (pip install matplotlib); tkinter comes with Python.
After saving: rebuild and flash the firmware.

APPS calibration: "Ligar VCU", then "Calibrar APPS" measures APPS1 with the pedal fully
pressed and released and writes APPS_MIN_BITS / APPS_MAX_BITS in APPS.h. Then rebuild and
flash from CubeIDE.

"Guardar config" / "Carregar config": the whole setup (map + every setting) in a JSON .cfg
file, in tools/configs by default. Loading fills the editor; "Gravar" writes it to the firmware.

Map units in the editor: accelerator and current in %, speed in km/h.
Map units in the file: per mille (0..1000 / -1000..1000), km/h.
Current > 0 = drive (SetRelCurrent), < 0 = regen (SetRelBrakeCurrent), 0 = coast.
"""

