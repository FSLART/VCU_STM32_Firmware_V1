BY_NAME = {s.name: s for s in SETTINGS}

# '#define NAME <number>[U|f]' followed only by spaces and an optional // comment
DEFINE_RE = r"^([ \t]*#define[ \t]+{name}[ \t]+)(-?\d+(?:\.\d+)?)([uUfF]?)(?=[ \t]*(?://[^\r\n]*)?\r?$)"


def read_file(rel):
    with open(
        ROOT / rel, encoding="utf-8", newline=""
    ) as f:  # newline="" keeps CRLF as is
        return f.read()


def find_define(text, name):
    """The match for '#define NAME <number>' if it is on exactly one plain line, else None."""
    matches = list(
        re.finditer(DEFINE_RE.format(name=re.escape(name)), text, flags=re.MULTILINE)
    )
    return matches[0] if len(matches) == 1 else None


def parse_value(setting, literal):
    """Number from the file, or None if it does not fit the setting's type."""
    try:
        value = float(literal) if setting.kind == "float" else int(literal)
    except ValueError:
        return None
    if setting.kind == "bool" and value not in (0, 1):
        return None
    return value


def read_settings():
    """{name: value}, with None for LOCKED settings. If any expected define of a file is
    missing, duplicated or not a plain number, all settings of that file are locked."""
    values = {}
    for rel in {s.file for s in SETTINGS}:
        names = [s.name for s in SETTINGS if s.file == rel]
        try:
            text = read_file(rel)
        except OSError:
            text = ""
        found = {}
        for name in names:
            match = find_define(text, name)
            found[name] = parse_value(BY_NAME[name], match.group(2)) if match else None
        file_ok = all(v is not None for v in found.values())
        values.update({name: (found[name] if file_ok else None) for name in names})
    return values


def check_settings(values):
    """[(file, message)] for out-of-range values and rule checks. None values are skipped."""
    errors = []
    for s in SETTINGS:
        v = values.get(s.name)
        if v is not None and not s.lo <= v <= s.hi:
            errors.append((s.file, f"{s.name} = {v:g} fora de {s.lo:g}..{s.hi:g}"))
    get = values.get
    lo, hi, tol = get("APPS_MIN_BITS"), get("APPS_MAX_BITS"), get("APPS_TOLERANCE")
    if None not in (lo, hi, tol):
        if hi <= lo:
            errors.append((APPS_H, "APPS_MIN_BITS tem de ser menor que APPS_MAX_BITS (senao o firmware nao compila)"))
        elif tol > (hi - lo) / 10:
            errors.append(
                (
                    APPS_H,
                    f"APPS_TOLERANCE > 10 % do curso do pedal ({(hi - lo) / 10:.0f} bits) - regra",
                )
            )
    travel, dead, margin = get("APPS_CAL_MIN_TRAVEL_BITS"), get("APPS_REST_DEADZONE_BITS"), get("APPS_FULL_MARGIN_BITS")
    if None not in (travel, dead, margin) and travel <= dead + margin:
        errors.append(
            (APPS_H, "APPS_CAL_MIN_TRAVEL_BITS tem de ser maior que zona morta + margem (senao o firmware nao compila)")
        )
    fade, cutoff = get("THROTTLE_REGEN_FADE_START_V"), get("THROTTLE_REGEN_CUTOFF_V")
    if None not in (fade, cutoff) and cutoff > 0 and fade >= cutoff:
        errors.append(
            (
                TC,
                "THROTTLE_REGEN_FADE_START_V tem de ser menor que THROTTLE_REGEN_CUTOFF_V (senao o firmware nao compila)",
            )
        )
    pau_lo, pau_hi = get("PAU_POWER_LIMIT_THRESHOLD_W"), get("PAU_MAX_POWER_W")
    if None not in (pau_lo, pau_hi) and pau_lo >= pau_hi:
        errors.append(
            (PAU, "PAU_POWER_LIMIT_THRESHOLD_W tem de ser menor que PAU_MAX_POWER_W (senao o firmware nao compila)")
        )
    return errors


APPS_CAL_SETTINGS = ("APPS_REST_DEADZONE_BITS", "APPS_FULL_MARGIN_BITS", "APPS_CAL_MIN_TRAVEL_BITS",
                     "APPS2_GAIN_X1000", "APPS_TOLERANCE")


def apps_cal_result(cal, values):
    """What APPS_Init() in APPS.c makes of a flash record {"rest"/"full": (apps1, apps2)}:
    (0 % bits, 100 % bits, APPS2 gain x1000, [problems]). Same checks as the firmware - a
    record it rejects is not used (the VCU falls back to the APPS.h values)."""
    (a1r, a2r), (a1f, a2f) = cal["rest"], cal["full"]
    dead, margin, travel, ref_gain, tol = (values[n] for n in APPS_CAL_SETTINGS)
    problems = []
    if a1f - a1r < travel or a2f - a2r < travel:
        problems.append(f"Curso do pedal menor que {travel} bits (APPS_CAL_MIN_TRAVEL_BITS): a VCU rejeita")
    gain = (a2f - a2r) * 1000 // (a1f - a1r) if a1f > a1r else 0
    if not ref_gain * 3 // 4 <= gain <= ref_gain * 5 // 4:
        problems.append(f"Ganho APPS2/APPS1 {gain / 1000:.3f} longe de {ref_gain / 1000:.3f} (+-25 %): a VCU rejeita")
    lo, hi = a1r + dead, a1f - margin
    if hi > lo and tol > (hi - lo) / 10:
        problems.append(f"APPS_TOLERANCE > 10 % do curso do pedal ({(hi - lo) / 10:.0f} bits) - regra")
    return lo, hi, gain, problems


def format_value(setting, value):
    if setting.kind != "float":
        return str(int(value))
    text = f"{value:.6g}"
    return text if ("." in text or "e" in text) else text + ".0"


def write_settings(new_values):
    """Write changed values in place, file by file. Returns (written_files, messages).
    Range and rule problems (check_settings) are only warnings and never stop the write.
    A file is skipped only if one of its #define lines no longer matches exactly once
    (the file changed since it was read) - writing it then would not be safe."""
    messages = []
    written = []
    for rel in sorted({BY_NAME[n].file for n in new_values}):
        text = read_file(rel)
        new_text = text
        for name, value in new_values.items():
            s = BY_NAME[name]
            if s.file != rel or value is None:
                continue
            match = find_define(new_text, name)
            if match is None:
                messages.append(f"{name}: linha do #define nao encontrada em {rel} - ficheiro nao gravado")
                new_text = None
                break
            if parse_value(s, match.group(2)) == value:
                continue
            literal = format_value(s, value)
            new_text = new_text[: match.start(2)] + literal + new_text[match.end(2) :]
        if new_text is not None and new_text != text:
            with open(ROOT / rel, "w", encoding="utf-8", newline="") as f:
                f.write(new_text)
            written.append(rel)
    return written, messages


def selftest():
    data = read_data()
    assert not validate(*data), validate(*data)
    tmp = DATA_FILE.with_suffix(".selftest.h")
    try:
        write_data(*data, path=tmp)
        assert read_data(tmp) == data, "map file does not read back the same"
    finally:
        tmp.unlink(missing_ok=True)

    values = read_settings()
    locked = [n for n, v in values.items() if v is None]
    assert not locked, f"locked (define line not found): {locked}"
    # Writing the same values must not touch any file
    written, _ = write_settings(dict(values))
    assert not written, f"unchanged values rewrote {written}"
    # A define that is missing or duplicated must lock
    assert find_define("#define X 1\n", "APPS_MIN_BITS") is None
    assert (
        find_define(
            "#define APPS_MIN_BITS 1\n#define APPS_MIN_BITS 2\n", "APPS_MIN_BITS"
        )
        is None
    )
    assert find_define("#define APPS_MIN_BITS (1 + 2)\n", "APPS_MIN_BITS") is None
    match = find_define("#define APPS_MIN_BITS 1118U  // c\r\n", "APPS_MIN_BITS")
    assert match is not None and match.group(2) == "1118"
    assert axis_bracket([0, 10, 20], -5) == (0, 1, 0.0)
    assert axis_bracket([0, 10, 20], 25) == (1, 2, 1.0)
    assert axis_bracket([0, 10, 20], 15) == (1, 2, 0.5)
    assert axis_bracket([0, 10, 20], 10) == (0, 1, 1.0)
    from vcu_live import pack_apps_cal, parse_apps_cal

    cal = {"rest": (1113, 2200), "full": (1375, 2705)}
    raw = pack_apps_cal(cal)
    assert parse_apps_cal(raw) == cal and parse_apps_cal(b"\xff" * len(raw)) is None
    assert parse_apps_cal(raw[:5] + bytes([raw[5] ^ 1]) + raw[6:]) is None, "CRC must catch a flipped bit"
    known = dict(values, APPS_REST_DEADZONE_BITS=9, APPS_FULL_MARGIN_BITS=8, APPS_CAL_MIN_TRAVEL_BITS=100,
                 APPS2_GAIN_X1000=1928, APPS_TOLERANCE=20)
    assert apps_cal_result(cal, known) == (1122, 1367, 1927, [])
    assert len(apps_cal_result({"rest": (1113, 2200), "full": (1150, 2270)}, known)[3]) == 2  # short travel
    problems = check_settings(values)
    print(
        f"OK - map {len(data[1])}x{len(data[0])}, {len(values)} settings found, none locked"
    )
    for _, msg in problems:
        print(f"  current value needs attention: {msg}")


