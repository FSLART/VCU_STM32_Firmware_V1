def cell_color(percent):
    """White at 0, red for drive, blue for regen, stronger with the value."""
    shade = int(255 * (1 - 0.65 * min(abs(percent) / 100, 1)))
    if percent > 0:
        return f"#ff{shade:02x}{shade:02x}"
    if percent < 0:
        return f"#{shade:02x}{shade:02x}ff"
    return "#ffffff"


