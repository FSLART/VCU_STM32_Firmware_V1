# ============================ MAP FILE FORMAT ============================


def read_data(path=DATA_FILE):
    """Return (apps_axis, speed_axis, table[speed][apps]) from the .h file."""
    text = re.sub(r"/\*.*?\*/|//[^\n]*", "", path.read_text(), flags=re.DOTALL)
    arrays = {
        name: [int(n) for n in re.findall(r"-?\d+", body)]
        for name, body in re.findall(
            r"(\w+)\s*\[[^=]*=\s*\{(.*?)\};", text, flags=re.DOTALL
        )
    }
    apps, speed = arrays["throttle_map_apps_axis"], arrays["throttle_map_speed_axis"]
    flat = arrays["throttle_map"]
    if len(flat) != len(apps) * len(speed):
        raise ValueError(f"{path.name}: array sizes do not match the axes")
    table = [flat[i * len(apps) : (i + 1) * len(apps)] for i in range(len(speed))]
    return apps, speed, table


def validate(apps, speed, table):
    """Return a list of problems with the map (empty = OK to write)."""
    errors = []
    if len(apps) < 2 or len(speed) < 2:
        errors.append("Each axis needs at least 2 points")
    if any(b <= a for a, b in pairwise(apps)) or apps[0] < 0 or apps[-1] > 1000:
        errors.append("Accelerator axis must increase strictly, 0..100 %")
    if any(b <= a for a, b in pairwise(speed)) or speed[0] < 0:
        errors.append("Speed axis must increase strictly, from 0 km/h")
    if any(not -1000 <= v <= 1000 for row in table for v in row):
        errors.append("Current must be between -100 % and 100 %")
    return errors


def write_data(apps, speed, table, path=DATA_FILE):
    width = max(len(str(v)) for row in table for v in row)
    rows = "\n".join(
        "    {" + ", ".join(f"{v:{width}d}" for v in row) + f"}},  // {s} km/h"
        for s, row in zip(speed, table)
    )
    join = lambda values: ", ".join(str(v) for v in values)
    path.write_text(
        TEMPLATE.format(
            na=len(apps), ns=len(speed), apps=join(apps), speed=join(speed), rows=rows
        )
    )


def write_config(path, apps, speed, table, settings):
    """Whole setup -> JSON .cfg. Map in file units (per mille, km/h), settings {name: value}."""
    cfg = {"map": {"apps": apps, "speed": speed, "table": table}, "settings": settings}
    text = json.dumps(cfg, indent=1)
    text = re.sub(r"\[\s+([-\d.,\s]+?)\s+\]", lambda m: "[" + " ".join(m.group(1).split()) + "]", text)
    Path(path).write_text(text, encoding="utf-8")  # one line per list of numbers (map row)


def read_config(path):
    """JSON .cfg -> ((apps, speed, table), {setting: value}). Settings this editor does not know,
    or that are not numbers, are left out. Raises ValueError/KeyError/TypeError if it is no config."""
    cfg = json.loads(Path(path).read_text(encoding="utf-8"))
    apps, speed, table = cfg["map"]["apps"], cfg["map"]["speed"], cfg["map"]["table"]
    if len(table) != len(speed) or any(len(row) != len(apps) for row in table):
        raise ValueError("mapa: o tamanho da tabela nao bate com os eixos")
    settings = {name: value for name, value in cfg.get("settings", {}).items()
                if name in BY_NAME and isinstance(value, (int, float))}
    return (apps, speed, table), settings


