    # ------------------------- Live link to the VCU -------------------------
    def set_live_cell(cell):
        """Green border on the table cell closest to the live operating point."""
        nonlocal live_cell, live_cell_default_hl
        if cell == live_cell:
            return
        if live_cell in entries:
            entries[live_cell].config(highlightthickness=live_cell_default_hl)
        live_cell = cell
        if cell in entries:
            live_cell_default_hl = int(entries[cell].cget("highlightthickness"))
            entries[cell].config(highlightthickness=3, highlightbackground="#00b000", highlightcolor="#00b000")

    def draw_live(values):
        """Green dot at the live pedal / speed / map value, and the nearest table cell."""
        nonlocal live_marker
        if live_marker is not None:
            live_marker.remove()
            live_marker = None
        pedal = values.get("throttle.pedal_1000")
        speed_now = values.get("throttle.speed_kmh")
        map_now = values.get("throttle.map_1000")
        if pedal is None or speed_now is None or map_now is None:
            return
        (live_marker,) = ax3d.plot([pedal / 10], [speed_now], [map_now / 10], linestyle="none", marker="o",
                                   markersize=11, markerfacecolor="#00d000", markeredgecolor="black",
                                   markeredgewidth=1.5, zorder=11)
        try:
            apps, speed, _ = collect_map()
        except ValueError:
            return
        col = min(range(len(apps)), key=lambda i: abs(apps[i] - pedal)) + 1
        row = min(range(len(speed)), key=lambda i: abs(speed[i] - speed_now)) + 1
        set_live_cell((row, col))
        canvas.draw_idle()

    def poll_live():
        link = live
        if link is None:
            return
        try:
            values = link.read()
        except Exception as err:  # noqa: BLE001 - probe unplugged, USB/pyocd error: message, not a crash
            disconnect_live(f"Ligacao a VCU perdida: {err}")
            return
        for v in link.variables:
            live_labels[v.expr].config(text=v.text(values[v.expr]))
        draw_live(values)
        root.after(200, poll_live)

    def disconnect_live(message):
        nonlocal live, live_marker
        link = live
        live = None
        if link is not None:
            with contextlib.suppress(Exception):  # probe may already be gone
                link.close()
        if live_marker is not None:
            live_marker.remove()
            live_marker = None
            canvas.draw_idle()
        set_live_cell(None)
        live_button.config(text="Ligar VCU")
        status.config(text=message, fg="black")

    def toggle_live():
        nonlocal live
        if live is not None:
            disconnect_live("Desligado da VCU")
            return
        try:
            sys.path.insert(0, str(Path(__file__).resolve().parent))
            from vcu_live import VcuLive

            link = VcuLive()
            link.connect()
        except Exception as err:  # noqa: BLE001 - any connect problem becomes a message
            messagebox.showerror("VCU ao vivo", str(err))
            return
        live = link
        for widget in live_frame.winfo_children():
            widget.destroy()
        live_labels.clear()
        for i, v in enumerate(link.variables):
            tk.Label(live_frame, text=v.label, anchor="w").grid(row=i, column=0, sticky="w")
            live_labels[v.expr] = tk.Label(live_frame, text="-", width=24, anchor="e", font=("Consolas", 10, "bold"))
            live_labels[v.expr].grid(row=i, column=1, sticky="e")
        for j, expr in enumerate(link.missing):
            tk.Label(live_frame, text=f"{expr}: nao existe no ELF", fg="gray").grid(
                row=len(link.variables) + j, column=0, columnspan=2, sticky="w")
        live_button.config(text="Desligar VCU")
        status.config(text="Ligado a VCU (ST-LINK) - so leitura", fg="green")
        poll_live()

    live_button = tk.Button(bar, text="Ligar VCU", width=12, command=toggle_live)
    live_button.pack(side="left", padx=4)

