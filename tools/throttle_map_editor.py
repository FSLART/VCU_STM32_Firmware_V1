    def on_release(event):
        """Click (not a rotation drag) on the 3D view: select the nearest point in the table."""
        start = press_start
        if (
            start is None
            or event.inaxes is not ax3d
            or abs(event.x - start[0]) > 3
            or abs(event.y - start[1]) > 3
        ):
            return
        try:
            apps, speed, table = collect_map()
        except ValueError:
            return
        # Project every grid point to screen pixels and take the closest one
        cells = [(r, c) for r in grid_size["rows"] for c in grid_size["cols"]]
        points = np.array(
            [
                [apps[c - 1] / 10, speed[r - 1], table[r - 1][c - 1] / 10, 1.0]
                for r, c in cells
            ]
        )
        projected = points @ ax3d.get_proj().T
        screen = ax3d.transData.transform(projected[:, :2] / projected[:, 3:4])
        distances = np.hypot(screen[:, 0] - event.x, screen[:, 1] - event.y)
        nearest = int(np.argmin(distances))
        if distances[nearest] <= 25:  # pixels
            move(*cells[nearest])

