    # ------------------------- Live link to the VCU -------------------------
    def mark_live(cells):
        """cells: {(row, col): 'strong' | 'weak' | 'axis'}. Undoes the previous marks first."""
        if cells.keys() == live_marked.keys():
            return
        for cell, (border, axis_bg) in live_marked.items():
            if cell in entries:
                entries[cell].config(highlightbackground=border, highlightcolor=border)
                if axis_bg is not None:
                    entries[cell].config(bg=axis_bg)
        live_marked.clear()
        for cell, style in cells.items():
            if cell not in entries:
                continue
            e = entries[cell]
            live_marked[cell] = (e.cget("highlightbackground"), e.cget("bg") if style == "axis" else None)
            if style == "axis":
                e.config(bg=LIVE_AXIS_BG)
            else:
                color = LIVE_STRONG if style == "strong" else LIVE_WEAK
                e.config(highlightbackground=color, highlightcolor=color)

    def draw_live(values):
        """ECU-style live cursor: green dot + trail in 3D; interpolation box and axes in the table."""
        nonlocal live_marker, live_trail_line
        for artist in (live_marker, live_trail_line):
            if artist is not None:
                artist.remove()
        live_marker = live_trail_line = None
        pedal = values.get("throttle.pedal_1000")
        speed_now = values.get("throttle.speed_kmh")
        map_now = values.get("throttle.map_1000")
        if pedal is None or speed_now is None or map_now is None:
            return
        point = (pedal / 10, speed_now, map_now / 10)
        live_trail.append(point)
        if len(live_trail) >= 2:
            # Fading trail: oldest segment almost transparent, newest strong
            points = list(live_trail)
            segments = [[points[k], points[k + 1]] for k in range(len(points) - 1)]
            colors = [(0.0, 0.6, 0.0, 0.1 + 0.8 * (k + 1) / len(segments)) for k in range(len(segments))]
            live_trail_line = Line3DCollection(segments, colors=colors, linewidths=1.5, zorder=10)
            ax3d.add_collection3d(live_trail_line)
        (live_marker,) = ax3d.plot([point[0]], [point[1]], [point[2]], linestyle="none", marker="o",
                                   markersize=11, markerfacecolor="#00d000", markeredgecolor="black",
                                   markeredgewidth=1.5, zorder=11)
        try:
            apps, speed, _ = collect_map()
        except ValueError:
            apps = speed = None
        if apps and speed:
            # The 4 cells the VCU interpolates between (same as throttle_map.c), heaviest one strongest
            c0, c1, fa = axis_bracket(apps, pedal)
            r0, r1, fs = axis_bracket(speed, speed_now)
            weights = {(r0 + 1, c0 + 1): (1 - fs) * (1 - fa), (r0 + 1, c1 + 1): (1 - fs) * fa,
                       (r1 + 1, c0 + 1): fs * (1 - fa), (r1 + 1, c1 + 1): fs * fa}
            heaviest = max(weights, key=lambda cell: weights[cell])
            cells = {cell: ("strong" if cell == heaviest else "weak") for cell in weights}
            cells.update({(0, c0 + 1): "axis", (0, c1 + 1): "axis", (r0 + 1, 0): "axis", (r1 + 1, 0): "axis"})
            mark_live(cells)
        canvas.draw_idle()

    def poll_live():
        nonlocal live_poll_job, live_failing_since
        live_poll_job = None
        link = live
        if link is None:
            return
        try:
            values = link.read()
        except Exception:  # noqa: BLE001 - SWD noise, probe unplugged, USB/pyocd error: retry, not a crash
            # Noise on SWCLK/SWDIO (inverters) makes single reads fail: keep the last values and retry
            now = time.monotonic()
            live_failing_since = live_failing_since or now
            if now - live_failing_since >= LIVE_LOST_TIMEOUT_S:
                # Still failing: reopen the ST-LINK. With the inverters on it can drop off USB and
                # come back seconds later, so keep trying every second until "Desligar VCU".
                try:
                    link.close()
                    link.connect()
                    live_failing_since = None
                except Exception as err:  # noqa: BLE001 - any connect problem becomes a message
                    status.config(text=f"Sem ligacao a VCU ha {now - live_failing_since:.0f} s - a tentar de novo "
                                       f"('Desligar VCU' para parar): {str(err).splitlines()[0]}", fg="#c06000")
                    live_poll_job = root.after(1000, poll_live)
                    return
            status.config(text=f"Sem leitura da VCU ha {now - (live_failing_since or now):.1f} s "
                               "(ruido no SWD?) - a tentar...", fg="#c06000")
            live_poll_job = root.after(200, poll_live)
            return
        if live_failing_since is not None:
            live_failing_since = None
            status.config(text="Ligacao a VCU recuperada", fg="green")
        for v in link.variables:
            live_labels[v.expr].config(text=v.text(values[v.expr]))
        draw_live(values)
        live_poll_job = root.after(200, poll_live)

    def disconnect_live(message):
        nonlocal live, live_marker, live_trail_line, live_poll_job, live_failing_since
        live_failing_since = None
        if live_poll_job is not None:
            root.after_cancel(live_poll_job)
            live_poll_job = None
        link = live
        live = None
        if link is not None:
            with contextlib.suppress(Exception):  # probe may already be gone
                link.close()
        for artist in (live_marker, live_trail_line):
            if artist is not None:
                artist.remove()
        live_marker = live_trail_line = None
        live_trail.clear()
        canvas.draw_idle()
        mark_live({})
        live_button.config(text="Ligar VCU")
        status.config(text=message, fg="black")

    def toggle_live():
        nonlocal live
        if live is not None:
            disconnect_live("Desligado da VCU")
            return
        try:
            sys.path.insert(0, str(Path(__file__).resolve().parent))
            from vcu_live import VcuLive

            link = VcuLive()
            link.connect()
        except Exception as err:  # noqa: BLE001 - any connect problem becomes a message
            messagebox.showerror("VCU ao vivo", str(err))
            return
        live = link
        for widget in live_frame.winfo_children():
            widget.destroy()
        live_labels.clear()
        rows = (len(link.variables) + 1) // 2  # two columns: the full list does not fit the window height
        for i, v in enumerate(link.variables):
            column = 2 * (i // rows)
            tk.Label(live_frame, text=v.label, anchor="w").grid(row=i % rows, column=column, sticky="w",
                                                                padx=(12 if column else 0, 0))
            live_labels[v.expr] = tk.Label(live_frame, text="-", width=24 if v.kind == "enum" else 8, anchor="e",
                                           font=("Consolas", 10, "bold"))
            live_labels[v.expr].grid(row=i % rows, column=column + 1, sticky="e")
        for j, expr in enumerate(link.missing):
            tk.Label(live_frame, text=f"{expr}: nao existe no ELF", fg="gray").grid(
                row=rows + j, column=0, columnspan=4, sticky="w")
        live_button.config(text="Desligar VCU")
        status.config(text="Ligado a VCU (ST-LINK) - so leitura", fg="green")
        poll_live()

    live_button = tk.Button(bar, text="Ligar VCU", width=12, command=toggle_live)
    live_button.pack(side="left", padx=4)

    def calibrate_apps():
        """Pedal fully pressed, then released -> APPS_MIN_BITS / APPS_MAX_BITS written in APPS.h."""
        title = "Calibrar APPS"
        link = live
        if link is None:
            messagebox.showinfo(title, "Liga primeiro a VCU ('Ligar VCU').")
            return
        if loaded.get("APPS_MIN_BITS") is None or loaded.get("APPS_MAX_BITS") is None:
            messagebox.showerror(title, "APPS.h bloqueado (#define nao encontrado) - nada a gravar.")
            return
        steps = (("full", "1/2  Carrega o pedal A FUNDO, mantem, e carrega OK.\n\nMede durante 1 s."),
                 ("rest", "2/2  Larga o pedal (repouso) e carrega OK.\n\nMede durante 1 s."))
        samples = {}
        try:
            for step, text in steps:
                if not messagebox.askokcancel(title, text) or live is not link:
                    status.config(text="Calibracao APPS cancelada", fg="black")
                    return
                status.config(text="A medir o APPS1...", fg="black")
                root.update_idletasks()
                end = time.monotonic() + APPS_CAL_SECONDS
                samples[step] = [link.read()["apps_data.state.apps1_raw"]]
                while time.monotonic() < end:
                    samples[step].append(link.read()["apps_data.state.apps1_raw"])
        except Exception as err:  # noqa: BLE001 - probe unplugged, USB/pyocd error: message, not a crash
            disconnect_live(f"Ligacao a VCU perdida: {err}")
            return
        lo, hi, warnings = apps_cal_defines(samples["full"], samples["rest"])
        new_values = {"APPS_MIN_BITS": lo, "APPS_MAX_BITS": hi}
        warnings += [m for f, m in check_settings({**loaded, **new_values}) if f == APPS_H]
        full, rest = samples["full"], samples["rest"]
        text = (f"A fundo:  APPS1 {min(full)}..{max(full)}, media {round(sum(full) / len(full))}\n"
                f"Repouso:  APPS1 {min(rest)}..{max(rest)}, media {round(sum(rest) / len(rest))}\n\n"
                f"APPS_MIN_BITS  {loaded['APPS_MIN_BITS']:g} -> {lo}   (media repouso + {APPS_CAL_MARGIN_BITS})\n"
                f"APPS_MAX_BITS  {loaded['APPS_MAX_BITS']:g} -> {hi}   (media a fundo - {APPS_CAL_MARGIN_BITS})\n\n")
        if warnings:
            text += "ATENCAO:\n" + "\n".join(f"- {w}" for w in warnings) + "\n\n"
        text += "Gravar no APPS.h?"
        if not messagebox.askyesno(title, text, icon="warning" if warnings else "question"):
            status.config(text="Calibracao APPS nao gravada", fg="black")
            return
        _, problems = write_settings(new_values)
        if problems:
            messagebox.showerror(title, "\n".join(problems))
            return
        for name, value in new_values.items():  # only these two fields: other unsaved edits stay
            loaded[name] = value
            fields[name][0].set(str(value))
        mark_settings()
        status.config(text=f"APPS.h gravado: 0 % = {lo}, 100 % = {hi} bits - compila e grava o firmware no CubeIDE",
                      fg="green")

    tk.Button(bar, text="Calibrar APPS", command=calibrate_apps).pack(side="left", padx=2)

